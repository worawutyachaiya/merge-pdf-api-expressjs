const jobTitle = `CASE
    WHEN J.MERGE_PDF_JOB_CODE REGEXP '^I[0-9]{2}-[0-9]{4,}$' THEN J.MERGE_PDF_JOB_CODE
    ELSE J.MERGE_PDF_JOB_TITLE
  END`

const jobSelect = `
  SELECT
    J.MERGE_PDF_JOB_ID AS JOB_ID,
    J.MERGE_PDF_JOB_CODE AS JOB_CODE,
    ${jobTitle} AS JOB_TITLE,
    J.MERGE_PDF_JOB_REFERENCE AS JOB_REFERENCE,
    J.INUSE, J.HAWB_OVERRIDE, J.STATUS, J.ROW_VERSION,
    J.STAMP_X, J.STAMP_Y, J.STAMP_FONT_SIZE, J.STAMP_STYLE,
    COALESCE((SELECT MAX(R.PUBLICATION_VERSION) FROM MERGE_PDF_PUBLICATION R
      WHERE R.MERGE_PDF_JOB_ID = J.MERGE_PDF_JOB_ID AND R.STATUS = 'PUBLISHED'), 0) AS REVISION_NO,
    J.CREATE_DATE, J.CREATE_BY, J.UPDATE_DATE, J.UPDATE_BY, J.LAST_COMPLETE_DATE AS LAST_COMPLETED_AT,
    (SELECT OUTPUT_FILE_NAME FROM MERGE_PDF_PUBLICATION R WHERE R.MERGE_PDF_JOB_ID = J.MERGE_PDF_JOB_ID
      AND R.STATUS = 'PUBLISHED' AND R.INUSE = 1 AND R.IS_CURRENT = 1 ORDER BY R.PUBLICATION_VERSION DESC LIMIT 1) AS OUTPUT_FILE_NAME,
    (SELECT NETWORK_PATH FROM MERGE_PDF_PUBLICATION R WHERE R.MERGE_PDF_JOB_ID = J.MERGE_PDF_JOB_ID
      AND R.STATUS = 'PUBLISHED' AND R.INUSE = 1 AND R.IS_CURRENT = 1 ORDER BY R.PUBLICATION_VERSION DESC LIMIT 1) AS NETWORK_PATH,
    (SELECT COUNT(*) FROM MERGE_PDF_DOCUMENT D WHERE D.MERGE_PDF_JOB_ID = J.MERGE_PDF_JOB_ID AND D.INUSE = 1 AND D.IS_CURRENT = 1) AS DOCUMENT_COUNT,
    (SELECT COUNT(*) FROM MERGE_PDF_PAGE P WHERE P.MERGE_PDF_JOB_ID = J.MERGE_PDF_JOB_ID AND P.INUSE = 1 AND P.IS_CURRENT = 1) AS PAGE_COUNT
  FROM MERGE_PDF_JOB J`

