  SELECT 1 FROM information_schema.COLUMNS
  WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'MERGE_PDF_FILE_SEQUENCE' AND COLUMN_NAME = 'FILE_SEQUENCE_ID'
), 'DO 0', 'ALTER TABLE MERGE_PDF_FILE_SEQUENCE
  ADD COLUMN FILE_SEQUENCE_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT FIRST,
  DROP PRIMARY KEY,
  ADD PRIMARY KEY (FILE_SEQUENCE_ID, REVISION_NO),
  ADD UNIQUE KEY UQ_MERGE_PDF_FILE_SEQUENCE_REVISION (PREFIX, REVISION_NO)');
