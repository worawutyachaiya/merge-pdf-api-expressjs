-- ALTER assigned an ID to each row. Reuse one ID for every revision of each entity.
-- Preserve the audit timestamps explicitly because UPDATE_DATE has ON UPDATE.
START TRANSACTION;

UPDATE MERGE_PDF_FILE_SEQUENCE AS revision
JOIN (
  SELECT PREFIX, MIN(FILE_SEQUENCE_ID) AS FILE_SEQUENCE_ID
  FROM MERGE_PDF_FILE_SEQUENCE GROUP BY PREFIX
) AS entity ON entity.PREFIX = revision.PREFIX
SET revision.FILE_SEQUENCE_ID = entity.FILE_SEQUENCE_ID, revision.UPDATE_DATE = revision.UPDATE_DATE
WHERE revision.FILE_SEQUENCE_ID <> entity.FILE_SEQUENCE_ID;

UPDATE MERGE_PDF_EMAIL_RECIPIENT AS revision
JOIN (
  SELECT EMPLOYEE_CODE, MIN(EMAIL_RECIPIENT_ID) AS EMAIL_RECIPIENT_ID
  FROM MERGE_PDF_EMAIL_RECIPIENT GROUP BY EMPLOYEE_CODE
) AS entity ON entity.EMPLOYEE_CODE = revision.EMPLOYEE_CODE
SET revision.EMAIL_RECIPIENT_ID = entity.EMAIL_RECIPIENT_ID, revision.UPDATE_DATE = revision.UPDATE_DATE
WHERE revision.EMAIL_RECIPIENT_ID <> entity.EMAIL_RECIPIENT_ID;

UPDATE MERGE_PDF_EMAIL_DIGEST_ITEM AS revision
JOIN (
  SELECT DIGEST_ID, QUEUE_ID, MIN(EMAIL_DIGEST_ITEM_ID) AS EMAIL_DIGEST_ITEM_ID
  FROM MERGE_PDF_EMAIL_DIGEST_ITEM GROUP BY DIGEST_ID, QUEUE_ID
) AS entity ON entity.DIGEST_ID = revision.DIGEST_ID AND entity.QUEUE_ID = revision.QUEUE_ID
SET revision.EMAIL_DIGEST_ITEM_ID = entity.EMAIL_DIGEST_ITEM_ID, revision.UPDATE_DATE = revision.UPDATE_DATE
WHERE revision.EMAIL_DIGEST_ITEM_ID <> entity.EMAIL_DIGEST_ITEM_ID;

UPDATE MERGE_PDF_EMAIL_DIGEST_RECIPIENT AS revision
JOIN (
  SELECT DIGEST_ID, EMPLOYEE_CODE, MIN(EMAIL_DIGEST_RECIPIENT_ID) AS EMAIL_DIGEST_RECIPIENT_ID
  FROM MERGE_PDF_EMAIL_DIGEST_RECIPIENT GROUP BY DIGEST_ID, EMPLOYEE_CODE
) AS entity ON entity.DIGEST_ID = revision.DIGEST_ID AND entity.EMPLOYEE_CODE = revision.EMPLOYEE_CODE
SET revision.EMAIL_DIGEST_RECIPIENT_ID = entity.EMAIL_DIGEST_RECIPIENT_ID, revision.UPDATE_DATE = revision.UPDATE_DATE
WHERE revision.EMAIL_DIGEST_RECIPIENT_ID <> entity.EMAIL_DIGEST_RECIPIENT_ID;

COMMIT;
