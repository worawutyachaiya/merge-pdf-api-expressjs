-- Apply only to the dedicated Merge PDF development database after the initial schema.
ALTER TABLE MERGE_PDF_PAGE
  ADD COLUMN CATEGORY_ID TINYINT UNSIGNED NULL AFTER DOCUMENT_ID,
  ADD COLUMN CLASSIFICATION_SOURCE VARCHAR(16) NULL AFTER CATEGORY_ID,
  ADD COLUMN CLASSIFICATION_CONFIDENCE DECIMAL(4,3) NULL AFTER CLASSIFICATION_SOURCE,
  ADD KEY IX_MERGE_PDF_PAGE_CATEGORY (JOB_ID, CATEGORY_ID),
  ADD CONSTRAINT FK_MERGE_PDF_PAGE_CATEGORY FOREIGN KEY (CATEGORY_ID)
    REFERENCES MERGE_PDF_CATEGORY (CATEGORY_ID),
  ADD CONSTRAINT CK_MERGE_PDF_PAGE_CLASSIFICATION CHECK
    (CLASSIFICATION_SOURCE IS NULL OR CLASSIFICATION_SOURCE IN ('AUTO_TEXT', 'AUTO_OCR', 'FILENAME', 'UNKNOWN', 'USER')),
  ADD CONSTRAINT CK_MERGE_PDF_PAGE_CONFIDENCE CHECK
    (CLASSIFICATION_CONFIDENCE IS NULL OR CLASSIFICATION_CONFIDENCE BETWEEN 0 AND 1);

ALTER TABLE MERGE_PDF_DOCUMENT
  DROP CHECK CK_MERGE_PDF_DOCUMENT_ENTRY_STATUS,
  ADD CONSTRAINT CK_MERGE_PDF_DOCUMENT_ENTRY_STATUS CHECK
    ((ENTRY_STATUS_CODE IS NULL AND ENTRY_STATUS_SOURCE IS NULL) OR
     (CATEGORY_ID IN (1, 10) AND ENTRY_STATUS_CODE IS NOT NULL AND
      ENTRY_STATUS_SOURCE IN ('USER', 'DOCUMENT', 'SYSTEM')));
