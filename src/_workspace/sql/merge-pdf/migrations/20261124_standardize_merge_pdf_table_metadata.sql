-- Run after 20261124_standardize_merge_pdf_table_ids.sql on the selected database.
-- Stop API and scheduler writes. Each ALTER renames its columns together.
SET @merge_pdf_ddl = IF(EXISTS (
  SELECT 1 FROM information_schema.COLUMNS
  WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'MERGE_PDF_CATEGORY' AND COLUMN_NAME = 'MERGE_PDF_CATEGORY_CODE'
), 'DO 0', 'ALTER TABLE MERGE_PDF_CATEGORY
  RENAME COLUMN CATEGORY_CODE TO MERGE_PDF_CATEGORY_CODE,
  RENAME COLUMN CATEGORY_NAME TO MERGE_PDF_CATEGORY_NAME');
PREPARE merge_pdf_ddl FROM @merge_pdf_ddl;
EXECUTE merge_pdf_ddl;
DEALLOCATE PREPARE merge_pdf_ddl;

SET @merge_pdf_ddl = IF(EXISTS (
  SELECT 1 FROM information_schema.COLUMNS
  WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'MERGE_PDF_JOB' AND COLUMN_NAME = 'MERGE_PDF_JOB_CODE'
), 'DO 0', 'ALTER TABLE MERGE_PDF_JOB
  RENAME COLUMN JOB_CODE TO MERGE_PDF_JOB_CODE,
  RENAME COLUMN JOB_TITLE TO MERGE_PDF_JOB_TITLE,
  RENAME COLUMN JOB_REFERENCE TO MERGE_PDF_JOB_REFERENCE');
PREPARE merge_pdf_ddl FROM @merge_pdf_ddl;
EXECUTE merge_pdf_ddl;
DEALLOCATE PREPARE merge_pdf_ddl;
