-- Convert ALL revisions, including cancelled jobs. Preserve existing custom coordinates.
UPDATE MERGE_PDF_JOB
SET STAMP_X = CASE SUBSTRING_INDEX(STAMP_POSITION, '_', -1)
      WHEN 'LEFT' THEN 0 WHEN 'CENTER' THEN 0.5 ELSE 1 END,
    STAMP_Y = CASE SUBSTRING_INDEX(STAMP_POSITION, '_', 1)
      WHEN 'TOP' THEN 0 WHEN 'MIDDLE' THEN 0.5 ELSE 1 END,
    UPDATE_DATE = UPDATE_DATE
WHERE STAMP_X IS NULL OR STAMP_Y IS NULL;

ALTER TABLE MERGE_PDF_JOB
  MODIFY COLUMN STAMP_X DOUBLE NOT NULL DEFAULT 1,
  MODIFY COLUMN STAMP_Y DOUBLE NOT NULL DEFAULT 0,
  DROP COLUMN STAMP_POSITION;
