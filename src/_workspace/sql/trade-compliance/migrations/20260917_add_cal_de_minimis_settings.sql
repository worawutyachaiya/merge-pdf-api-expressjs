CREATE TABLE IF NOT EXISTS CAL_DE_MINIMIS_SETTING (
  CAL_DE_MINIMIS_SETTING_ID INT NOT NULL AUTO_INCREMENT,
  SETTING_CODE VARCHAR(30) NOT NULL,
  US_ORIGIN_THRESHOLD_PERCENT DECIMAL(9,4) NOT NULL DEFAULT 25.0000,
  FEC_CONTROLLED_THRESHOLD_PERCENT DECIMAL(9,4) NOT NULL DEFAULT 10.0000,
  CREATE_BY VARCHAR(30) NOT NULL,
  CREATE_DATE DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATE_BY VARCHAR(30) NOT NULL,
  UPDATE_DATE DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INUSE TINYINT(1) NOT NULL DEFAULT 1,
  PRIMARY KEY (CAL_DE_MINIMIS_SETTING_ID),
  UNIQUE KEY UQ_CAL_DE_MINIMIS_SETTING_CODE (SETTING_CODE),
  CONSTRAINT CK_CAL_DE_MINIMIS_US_THRESHOLD CHECK (US_ORIGIN_THRESHOLD_PERCENT BETWEEN 0 AND 100),
  CONSTRAINT CK_CAL_DE_MINIMIS_FEC_THRESHOLD CHECK (FEC_CONTROLLED_THRESHOLD_PERCENT BETWEEN 0 AND 100)
);

INSERT INTO CAL_DE_MINIMIS_SETTING (
  SETTING_CODE,
  US_ORIGIN_THRESHOLD_PERCENT,
  FEC_CONTROLLED_THRESHOLD_PERCENT,
  CREATE_BY,
  UPDATE_BY
)
VALUES ('DEFAULT', 25.0000, 10.0000, 'SYSTEM', 'SYSTEM')
ON DUPLICATE KEY UPDATE INUSE = 1;
