const eligibleQueue = `FROM MERGE_PDF_EMAIL_QUEUE Q
  JOIN MERGE_PDF_JOB J ON J.JOB_ID = Q.JOB_ID AND J.INUSE = 1 AND J.IS_CURRENT = 1
  JOIN MERGE_PDF_PUBLICATION P ON P.PUBLICATION_ID = Q.PUBLICATION_ID AND P.INUSE = 1 AND P.IS_CURRENT = 1 AND P.STATUS = 'PUBLISHED'
  WHERE Q.INUSE = 1 AND Q.IS_CURRENT = 1 AND Q.STATUS = 'PENDING' AND P.NETWORK_PATH IS NOT NULL
    AND NOT EXISTS (SELECT 1 FROM MERGE_PDF_EMAIL_DIGEST_ITEM I WHERE I.QUEUE_ID = Q.QUEUE_ID)`

